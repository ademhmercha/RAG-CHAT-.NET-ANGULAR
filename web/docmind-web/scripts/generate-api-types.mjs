import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const snapshotPath = resolve(root, 'openapi/openapi.json');
const outputPath = resolve(root, 'src/app/core/api/schema.d.ts');
const apiUrl = process.env['API_URL'] ?? 'http://localhost:5080';
const offline = process.argv.includes('--offline');

function normalizeNumbers(node) {
  if (Array.isArray(node)) {
    return node.map(normalizeNumbers);
  }

  if (node && typeof node === 'object') {
    const types = Array.isArray(node.type) ? node.type : null;
    if (types?.includes('string') && (types.includes('integer') || types.includes('number'))) {
      const { pattern, ...rest } = node;
      return normalizeNumbers({ ...rest, type: types.includes('integer') ? 'integer' : 'number' });
    }

    return Object.fromEntries(Object.entries(node).map(([key, value]) => [key, normalizeNumbers(value)]));
  }

  return node;
}

function pinApiVersion(document) {
  const paths = {};

  for (const [path, item] of Object.entries(document.paths ?? {})) {
    const pinned = path.replace('/api/v{version}/', '/api/v1/');
    const operations = {};

    for (const [method, operation] of Object.entries(item)) {
      operations[method] =
        operation && typeof operation === 'object' && Array.isArray(operation.parameters)
          ? { ...operation, parameters: operation.parameters.filter((p) => p.name !== 'version') }
          : operation;
    }

    paths[pinned] = operations;
  }

  return normalizeNumbers({ ...document, paths });
}

async function loadDocument() {
  if (offline) {
    return JSON.parse(readFileSync(snapshotPath, 'utf8'));
  }

  const response = await fetch(`${apiUrl}/openapi/v1.json`);
  if (!response.ok) {
    throw new Error(`GET ${apiUrl}/openapi/v1.json answered ${response.status}. Is the backend running with Documentation:Enabled?`);
  }

  const document = pinApiVersion(await response.json());
  mkdirSync(dirname(snapshotPath), { recursive: true });
  writeFileSync(snapshotPath, `${JSON.stringify(document, null, 2)}\n`);
  return document;
}

const document = offline ? pinApiVersion(await loadDocument()) : await loadDocument();
const ast = await openapiTS(document);

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `/* eslint-disable */\n// Generated by scripts/generate-api-types.mjs from openapi/openapi.json. Do not edit.\n${astToString(ast)}`,
);

console.log(`API types written to ${outputPath}${offline ? ' (from the committed snapshot)' : ` (from ${apiUrl})`}`);
